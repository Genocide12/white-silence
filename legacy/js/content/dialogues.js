  function hint(text) {
    if (WS.Ui && WS.Ui.hint) {
      try { WS.Ui.hint(text); } catch (e) { /* пусто */ }
    }
  }

  function hitInteract() {
    if (!WS.Input || !WS.Input.hit) return false;
    try { return WS.Input.hit('interact'); } catch (e) { return false; }
  }

  function noOtherInteract() {
    if (WS.Action && WS.Action.interactTarget) {
      try {
        var t = WS.Action.interactTarget();
        if (t) return false;
      } catch (e) { /* пусто */ }
    }
    return true;
  }

  function interceptTick(dt) {
    var g = G();
    if (!g || !g.running || g.dead) return;
    if (WS.Ui && WS.Ui.modal && WS.Ui.modal()) return;
    var p = P();
    if (!p || p.sleeping) return;

    // ---- пёс: до events.js (тик 45), чтобы разговор шёл через WS.Dialog ----
    var dog = findDog();
    if (dog) {
      var dd = WS.M.dist(p.x, p.y, dog.x, dog.y);
      if (dd < 2.5 && noOtherInteract()) {
        hint(dog.tamed ? 'Пёс вертится у ног' : 'Пёс смотрит на вас');
        if (hitInteract()) {
          WS.Dialog.start({
            name: 'Пёс',
            sprName: 'dog',
            sprFrame: 0,
            portraitFrames: [0, 1],
            cap: 'не говорит по-человечески',
            optsHint: false,
            tree: dogTree
          });
        }
        return;
      }
    }

    // ---- Ванятка: до story.js (тик 63) ----
    var boy = findBoy();
    if (boy && !fg('child_dead') && fg('child_intro')) {
      var bd = WS.M.dist(p.x, p.y, boy.x, boy.y);
      if (bd < 1.9 && noOtherInteract()) {
        hint(fg('child_saved') ? 'Ваня спит спокойно' : 'Поговорить с Ваняткой');
        if (hitInteract()) {
          WS.Dialog.start(vanyaNpc(boy));
        }
        return;
      }
    }
  }

