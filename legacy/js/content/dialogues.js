  var extraNodes = {};   // npcId -> { nodes: {id: node}, entry: option | null }

  function registerExtra(npcId, nodes, entry) {
    if (!npcId || !nodes) return;
    if (!extraNodes[npcId]) extraNodes[npcId] = { nodes: {}, entry: null };
    var box = extraNodes[npcId];
    for (var k in nodes) {
      if (nodes.hasOwnProperty(k)) box.nodes[k] = nodes[k];
    }
    if (entry) box.entry = entry;
  }

  /** Дописать узлы в готовое дерево (узлы с тем же id расширяются). */
  function mergeExtra(tree, npcId) {
    var box = extraNodes[npcId];
    if (!tree || !tree.nodes || !box) return tree;
    var nodes = tree.nodes;
    for (var k in box.nodes) {
      if (!box.nodes.hasOwnProperty(k)) continue;
      if (nodes[k]) {
        // узел уже есть — добавляем варианты в конец
        var opts = box.nodes[k].options;
        if (opts && opts.length) {
          nodes[k].options = (nodes[k].options || []).concat(opts);
        }
      } else {
        nodes[k] = box.nodes[k];
      }
    }
    if (box.entry) {
      var host = nodes.main || nodes[tree.start];
      if (host) {
        host.options = host.options || [];
        host.options.unshift(box.entry);
      }
    }
    return tree;
  }

