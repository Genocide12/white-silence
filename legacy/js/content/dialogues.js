  /** Дать вещь из квеста E1: списать, поднять флаг, проверить спасение. */
  function giveChildItem(kind) {
    var map = {
      q: { item: 'quinine', flag: 'child_q', txt: 'Дать хинин' },
      v: { item: 'child_valenki', flag: 'child_v', txt: 'Надеть валенки' },
      k: { item: 'kasha', flag: 'child_k', txt: 'Покормить кашей' }
    };
    var m = map[kind];
    if (!m) return 'v_main';
    if (fg(m.flag)) return 'v_have_' + kind;
    if (invConsume(m.item, 1) < 1) return 'v_none';

    fs(m.flag, 1);
    if (kind === 'q') {
      toast('«Горько-о-о...» — мальчик сморщился, но проглотил порошок.', 'good');
      chron('Дал Ванятке хинин. Жар должен спасть.', 'find');
      snd('eat', 0.4);
    } else if (kind === 'v') {
      toast('Валенки пришлись впору. Ноги больше не синие.', 'good');
      chron('Утеплил Ванятке ноги валенками.', 'find');
      snd('craft', 0.4);
    } else {
      toast('«С солью... как мамка делала...» — он ел медленно и уснул на ложке.', 'good');
      chron('Накормил Ванятку горячей кашей.', 'find');
      snd('eat', 0.5);
    }

    // всё ли собрано? (зеркало childProgress из story.js — её не трогаем)
    if (fg('child_q') && fg('child_v') && fg('child_k') && !fg('child_saved')) {
      fs('child_saved', 1);
      fs('child_resolved', 1);
      var boy = findBoy();
      if (boy) {
        boy.sprFrame = 1;
        boy.state = 'saved';
      }
      addSanity(15);
      toast('К утру жар спал. Ваня спит, щёки порозовели. Он выживет.', 'good');
      chron('Мальчик спасён. Жар отступил, он спит спокойно.', 'find');
      snd('bell', 0.6);
      try { WS.Ev.emit('story:child_saved', { day: day() }); }
      catch (e) { WS.err('dialogues: child_saved emit', e && e.message); }
    }
    return 'v_gave_' + kind;
  }

