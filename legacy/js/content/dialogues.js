  /** Можно ли развести огонь (для условий Фёдора). */
  function fedorCanFire() {
    var Wb0 = Wb();
    if (Wb0.fireNearFedor && Wb0.fireNearFedor()) return true;
    var hasFire = (invCount('matches') > 0 || invCount('flint') > 0);
    var hasWood = (invCount('log') > 0 || invCount('firewood_bundle') > 0 ||
                   invCount('plank') > 0 || invCount('branch') > 0);
    var hasTinder = (invCount('dry_grass') > 0 || invCount('newspaper_stack') > 0 ||
                     invCount('birch_bark') > 0 || invCount('wadding') > 0 ||
                     invCount('candle_stump') > 0);
    return hasFire && hasWood && hasTinder;
  }

