  /** Самотест (консоль): деревья собираются, узлы целостны. */
  function selftest() {
    var out = [];
    var ok = function (name, cond) {
      out.push((cond ? '  ok  ' : ' FAIL ') + name);
      return !!cond;
    };

    var checkTree = function (name, t) {
      var good = !!(t && t.nodes && t.start && t.nodes[t.start]);
      if (good) {
        // каждый next ведёт в существующий узел (или option.end)
        var nodes = t.nodes;
        for (var id in nodes) {
          if (!nodes.hasOwnProperty(id)) continue;
          var opts = nodes[id].options || [];
          for (var i = 0; i < opts.length; i++) {
            var o = opts[i];
            if (!o || o.end) continue;
            var nx = (typeof o.next === 'function') ? null : o.next;
            if (nx !== null && nx !== undefined && !nodes[nx]) {
              good = false;
              WS.warn('dialogues: ' + name + ': option "' + (o.txt || '?') +
                      '" ведёт в пустоту: ' + nx);
            }
          }
        }
      }
      ok('дерево «' + name + '» целостно', good);
      return good;
    };

    checkTree('semen (прячется)', (function () {
      var saved = WS.G;
      WS.G = { story: { flags: {}, rep: {}, notes: [] } };
      var t = semenTree();
      WS.G = saved;
      return t;
    })());
    checkTree('semen (вышел)', (function () {
      var saved = WS.G;
      WS.G = { story: { flags: { wr_semen_out: 1 }, rep: { semen: 4 }, notes: [] } };
      var t = semenTree();
      WS.G = saved;
      return t;
    })());
    checkTree('matrena', matrenaTree());
    checkTree('fedor (замерзает)', (function () {
      var saved = WS.G;
      WS.G = { story: { flags: { wr_fedor: 'lost' }, rep: {}, notes: [] } };
      var t = fedorTree();
      WS.G = saved;
      return t;
    })());
    checkTree('fedor (спасён)', (function () {
      var saved = WS.G;
      WS.G = { story: { flags: { wr_fedor: 'saved' }, rep: {}, notes: [] } };
      var t = fedorTree();
      WS.G = saved;
      return t;
    })());
    checkTree('horse', horseTree());
    checkTree('vanya', vanyaTree());
    checkTree('dog', dogTree());

    ok('доп-дерево Акима зарегистрировано', !!extraNodes.hermit);
    ok('механизм registerExtra объявлен',
      typeof WS.Dialog.registerExtra === 'function');
    ok('repAdd с именами установлен', typeof WS.Dialog.repAdd === 'function');

    out.unshift('dialogues.selftest: пройдено');
    return out;
  }

