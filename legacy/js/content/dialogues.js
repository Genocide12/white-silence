  WS.boot(function initDialogues() {
    // 1) репутация с человеческими именами (то же хранилище, тот же смысл)
    if (WS.Dialog && WS.Dialog.repAdd) {
      WS.Dialog.repAdd = namedRepAdd;
    }

    // 2) механизм доп-деревьев: WS.Dialog.registerExtra + обёртка start
    if (WS.Dialog && !WS.Dialog.registerExtra) {
      WS.Dialog.registerExtra = function (npcId, nodes, entry) {
        registerExtra(npcId, nodes, entry);
      };
    }
    if (WS.Dialog && WS.Dialog.start) {
      var origStart = WS.Dialog.start;
      WS.Dialog.start = function (npc) {
        try {
          if (npc && npc.repId && extraNodes[npc.repId]) {
            var id = npc.repId;
            var copy = {};
            for (var k in npc) {
              if (npc.hasOwnProperty(k)) copy[k] = npc[k];
            }
            var origTree = npc.tree;
            copy.tree = function (c) {
              var t = (typeof origTree === 'function') ? origTree(c) : origTree;
              return mergeExtra(t, id);
            };
            npc = copy;
          }
        } catch (e) {
          WS.err('dialogues: extra-merge не удался:', e && e.message);
        }
        return origStart.call(WS.Dialog, npc);
      };
    }

    // 3) доп-дерево старца Акима (его файл не трогаем)
    registerHermitExtra();

    // 4) перехват [E]: пёс и Ванятка (до events.js:45 и story.js:63)
    WS.tick(44, interceptTick, 'dialogues:intercept');

    WS.log('[Dialogues] деревья разговоров готовы: Семён, Матрёна, Фёдор, Вишня, Ванятка, пёс, доп-темы Акима');
  }, 'dialogues:init');

