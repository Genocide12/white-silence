  // ====================================================================
  //  ВОЛК-ВОЖАК (volk_alpha), 60x36
  //  На четверть крупнее рядового волка (48x28): шире корпус, тяжелее
  //  загривок, тёмная мантия по хребту и шрам через скулу на морду.
