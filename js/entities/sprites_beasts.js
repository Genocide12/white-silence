    px(c, 50, 0 + dy, 4, 5, W1);
    px(c, 45, 1 + dy, 2, 3, WD);
    px(c, 51, 1 + dy, 2, 3, WD);

    // морда — крупная, тяжёлая нижняя челюсть
    px(c, 54, 8 + dy, 6, 5, WD);
