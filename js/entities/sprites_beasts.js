    px(c, 19, 38, 5, 6, WD);
    px(c, 12, 42, 5, 2, WS0);
    px(c, 19, 42, 5, 2, WS0);

    // круп на земле
    px(c, 7, 26, 16, 14, W1);
    px(c, 8, 25, 13, 2, W2);
    px(c, 7, 37, 15, 2, WD);

    // длинная шерсть свисает с груди
    px(c, 20, 24, 2, 4, WD);
    px(c, 24, 26, 2, 3, WD);
    // хвост подметает снег перед лапами
    px(c, 3, 38, 12, 4, W1);
    px(c, 2, 40, 6, 3, W2);
    // припорошенный след под хвостом
    px(c, 6, 43, 8, 1, SNOWCAP);

    // спина — дуга к загривку
    px(c, 14, 20, 12, 10, W1);
    px(c, 15, 19, 10, 2, W2);

    // грудь: рёбра расправляются на вой
    px(c, 19, 18 - br, 8, 16 + br, W1);
    px(c, 20, 16 - br, 6, 3, W2);

    // шея взмывает вверх
    px(c, 22, 8 + hy, 8, 12, W1);
    px(c, 23, 7 + hy, 6, 2, W2);

    // голова запрокинута к небу
    px(c, 23, 2 + hy, 10, 8, W1);
    px(c, 24, 1 + hy, 8, 2, W2);

    // уши прижаты назад по шее
    px(c, 20, 6 + hy, 4, 3, WD);
    px(c, 24, 4 + hy, 4, 3, WD);

    // верхняя морда — к звёздам
    px(c, 30, 1 + hy, 6, 4, WD);
    px(c, 35, 2 + hy, 2, 2, NOSE);

    // пасть — поёт: нижняя челюсть отвисла
    px(c, 28, 6 + hy, 7, 2, THROT);
    if (up) {
      px(c, 28, 7 + hy, 7, 1, '#0e1014');   // зев шире на выводе
      px(c, 30, 8 + hy, 3, 1, THROT);       // горло вибрирует
    }

    // клыки воют
    px(c, 29, 6 + hy, 1, 1, TOOTH);
    px(c, 33, 6 + hy, 1, 1, TOOTH);

    // глаз прикрыт — волк поёт
    px(c, 25, 4 + hy, 2, 1, WS0);

    // морозный пар дыхания над мордой (виден на выводе звука)
