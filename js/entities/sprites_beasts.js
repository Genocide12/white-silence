  Spr.def('volk_alpha', {
    w: 60, h: 36,
    draw: function (c, w, h, frame, dir, variant) {
      var f = (frame | 0) & 3;
      var d = dir4(dir);
      if (d === 6) mirror(c, w, function () { volkAlphaSide(c, f); });
      else if (d === 2) volkAlphaSide(c, f);
      else if (d === 0) volkAlphaUp(c, f);
      else volkAlphaDown(c, f);
      // вариант 1 — раненый вожак: кровь на шкуре
      if (variant & 1) {
        if (d === 6) mirror(c, w, function () { volkAlphaBloodSide(c); });
        else if (d === 2) volkAlphaBloodSide(c);
        else if (d === 0) volkAlphaBloodUp(c);
        else volkAlphaBloodDown(c);
      }
    }
  });

