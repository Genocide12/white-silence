  function R2(c, x, y, w, h, col) {
    c.fillStyle = col;
    c.fillRect(x * 2, y * 2, w * 2, h * 2);
  }
  function E2(c, x, y, rx, ry, col) {
    c.fillStyle = col;
    c.beginPath();
    c.ellipse(x * 2, y * 2, rx * 2, ry * 2, 0, 0, Math.PI * 2);
    c.fill();
  }
  function D2(c, x, y, col) {
    c.fillStyle = col;
    c.fillRect(x * 2, y * 2, 2, 2);
  }
  /** Пиксельная заливка 1:1 для мелкой живности. */
  function p(c, x, y, w, h, col) {
    c.fillStyle = col;
    c.fillRect(x, y, w, h);
  }
  /** Зеркало по горизонтали (запад = восток). */
  function mirror(c, w, fn) {
    c.save();
    c.translate(w, 0);
    c.scale(-1, 1);
    fn();
    c.restore();
  }

