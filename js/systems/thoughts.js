  function classifyObj(o) {
    if (!o) return null;
    var spr = o.sprName || '';
    var name = o.name || '';
    if (o.note) return 'new_found_note';           // записка/письмо (рой)
    if (o.radio || spr === 'radio_recv') return 'radio';
    if (/stove|pech|pechka/i.test(spr) || /Печь/i.test(name)) return o.lit ? 'stove_lit' : 'stove';
    if (/bed/i.test(spr) || /Кроват|Тахт/i.test(name)) return 'bed';
    if (spr === 'crazy_gift') return 'gift';
    if (o.door) return o.locked && !o.open ? 'locked_door' : null;
    if (o.container) return 'container';
    if (/ice_hole|polynya/i.test(spr) || /Прорубь|Полынь/i.test(name)) return 'ice_hole';
    if (/tree|fir|pine|birch|spruce/i.test(spr)) return 'tree';
    return null;
  }

  function perceiveTick() {
    var p = P();
    if (!p || !running() || modal()) return;
    var w = WS.World;
    if (!w || !w.objects) return;
    var now = Date.now();

    // ЗАБЛУДИЛСЯ (рой): далеко от посёлка и темнеет — дед ищет ориентиры
    try {
      var V = (WS.AI && WS.AI.village) ? WS.AI.village : { x: 110, y: 115 };
      var hNow = (WS.Time && WS.Time.hourF) ? WS.Time.hourF() : 12;
      var dark = hNow >= 17.5 || hNow <= 6.5;
      if (dark && dist(p.x, p.y, V.x, V.y) > 42) think('new_lost_forest');
    } catch (eL) { /* пусто */ }

    // дым из трубы рядом (тёплый дом) — по зданиям не пробегаемся,
    // ловим через World.buildings, если есть
    try {
      if (w.buildings && w.buildings.length) {
        for (var bi = 0; bi < w.buildings.length; bi++) {
          var bld = w.buildings[bi];
          if (!bld || !bld.heated) continue;
          if (dist(p.x, p.y, bld.cx || bld.x || 0, bld.cy || bld.y || 0) > PERCEIVE_R + 3) continue;
          if (!S.seen['warm'] || now - S.seen['warm'] > 250000) {
            S.seen['warm'] = now;
            think('building_warm');
            return;
          }
        }
      }
    } catch (e) { /* пусто */ }

    var bestKind = null, bestPrio = 0;
    for (var i = 0; i < w.objects.length; i++) {
      var o = w.objects[i];
      if (!o) continue;
      if (dist(p.x, p.y, o.x, o.y) > PERCEIVE_R) continue;
      var kind = classifyObj(o);
      if (!kind) continue;
      if (kind === 'stove' || kind === 'stove_lit') {
        // холодному деду печь интереснее
        var coldish = (p.temp || 36.6) < 35.9 || (WS.Crazy && WS.Crazy.active && (WS.Crazy.state().hpShadow < 45));
        if (kind === 'stove' && coldish) kind = 'stove_cold';
        else if (kind === 'stove') kind = 'stove_ok';
      }
      if (kind === 'container') kind = 'container_first';
      var meta = META[kind] || {};
      var pr = meta.prio || 1;
      if (pr > bestPrio) { bestPrio = pr; bestKind = kind; }
    }
    if (!bestKind) return;
    // не чаще раза на класс
    var seenAt = S.seen[bestKind] || 0;
    var meta2 = META[bestKind] || {};
    if (now - seenAt < (meta2.cd || DEF_COOLDOWN) * 1000) return;
    S.seen[bestKind] = now;
    think(bestKind);
  }

