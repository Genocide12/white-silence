  function think(key, opt) {
    if (!S.enabled) return null;
    opt = opt || {};
    var list = listFor(key);
    if ((!list || !list.length) && !opt.text) return null;
    var meta = META[key] || {};
    var now = Date.now();
    var cd = (opt.cd || meta.cd || DEF_COOLDOWN) * 1000;
    if (S.lastByKey[key] && now - S.lastByKey[key] < cd) return null;
    // общая пауза: опасность (prio 3) её игнорирует
    var prio = opt.prio != null ? opt.prio : (meta.prio || 1);
    if (prio < 3 && now - S.lastThought < GLOBAL_GAP * 1000) return null;

    // Не повторять одну и ту же фразу подряд: если выпала та же, что
    // в прошлый раз в этой категории — перекрутим один раз (жалоба
    // «мало фраз и они глупые»: повторы убивают ощущение живого деда).
    var text = opt.text || rnd(list);
    if (!opt.text && list && list.length > 1) {
      var first = text;
      if (S.lastTextByKey[key] === first) {
        var second = rnd(list);
        if (second !== first) text = second;
      }
    }
    // подстановки: {item}, {days}, {left} — фраза умнее, чем шаблон
    if (opt.vars) {
      text = text.replace(/\{item\}/g, opt.vars.item || 'всякое')
                 .replace(/\{days\}/g, String(opt.vars.days != null ? opt.vars.days : '?'))
                 .replace(/\{left\}/g, String(opt.vars.left != null ? opt.vars.left : '?'));
    }
    S.lastByKey[key] = now;
    S.lastTextByKey[key] = text;
    S.lastThought = now;

    showBubble(text);
    if (!opt.silent) speak(text, { force: prio >= 3 });

    // в демо — пишем мысль в журнал (пользователь потом читает)
    try {
      if (WS.Demo && WS.Demo.active && WS.Demo.active() && WS.Demo.thoughtLog) {
        WS.Demo.thoughtLog(text);
      }
    } catch (e) { /* пусто */ }
    return text;
  }

  /** Произнести конкретный текст как мысль деда (вне базы). */
  function thinkText(text, key, opt) {
    opt = opt || {};
    opt.text = text;
    return think(key || '_custom', opt);
  }

