  var HOSTILE = { wolf: 'wolf', bear: 'bear', bandit: 'bandit' };

  function dangerTick() {
    var p = P();
    if (!p || !running() || modal()) return;
    var w = WS.World;
    if (!w || !w.ents) return;
    var now = Date.now();
    var spotted = {}, near = {}, howl = false;
    for (var i = 0; i < w.ents.length; i++) {
      var e = w.ents[i];
      if (!e || e.dead) continue;
      var k = HOSTILE[e.kind];
      if (!k) continue;
      var d = dist(p.x, p.y, e.x, e.y);
      if (d > DANGER_R) continue;
      var aims = (e.target === p) || (e.mode === 'chase') || (e.mode === 'attack');
      if (d < 9 && aims) spotted[k] = true;
      else if (d < DANGER_R * 0.7) near[k] = true;
      // ВОЙ ВДАЛИ (рой): волк далеко, но ночью слышно — мурашки
      if (k === 'wolf' && d >= 12 && d <= 28 && (WS.Time && WS.Time.light && WS.Time.light() < 0.3)) howl = true;
    }
    if (howl) think('new_wolf_howl');
    ['wolf', 'bear', 'bandit'].forEach(function (k) {
      var key = k + (spotted[k] ? '_spotted' : '_near');
      if ((spotted[k] || near[k]) && (!S.dangerSeen[key] || now - S.dangerSeen[key] > (META[key].cd || 45) * 1000)) {
        if (think(key)) S.dangerSeen[key] = now;
      }
    });
  }

