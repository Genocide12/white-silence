  /** Применить блок расширений, вернуть статистику. */
  function applyExt(block, label) {
    var applied = 0, missing = 0, items = 0;
    for (var tableId in block) {
      if (!block.hasOwnProperty(tableId)) continue;
      var res = extend(tableId, block[tableId]);
      if (res) { applied++; items += res.added; }
      else missing++;
    }
    if (missing) WS.warn('loot:tables2 (' + label + '): таблиц не найдено: ' + missing);
    return { applied: applied, items: items, missing: missing };
  }

  /** Применить все новые таблицы. */
  function applyNew() {
    var n = 0;
    for (var tableId in NEW) {
      if (!NEW.hasOwnProperty(tableId)) continue;
      if (add(tableId, NEW[tableId].rolls, NEW[tableId].items)) n++;
    }
    return n;
  }

  /**
   * Самопроверка (после первого кадра — все boot отработали, включая
   * recipes.js с fallback-предметами и loot_professions.js с трофеями):
   *   - каждая НАША таблица существует;
   *   - НОВЫЕ таблицы: каждый id существует, «пусто» присутствует;
   *   - РАСШИРЕНИЯ: проверяем только ДОБАВЛЕННЫЕ нами id (базовые
   *     записи loot_tables.js — не наша зона ответственности: там
   *     есть предметы «из i18n без спеки» — telegraph_form и пр.,
   *     движок их терпит осознанно).
   * Список проблем — в консоль (WS.warn), игра не валидится.
   */
  function selfTest() {
    var bad = [];
    var loot = (WS.Data && WS.Data.loot) || {};
    var items = (WS.Data && WS.Data.items) || {};

    function checkId(where, id) {
      if (!items[id]) bad.push(where + ': нет предмета ' + id);
    }

    // новые таблицы — полностью наши
    var k, i;
    for (k in NEW) {
      if (!NEW.hasOwnProperty(k)) continue;
      var t = loot[k];
      if (!t) { bad.push(k + ': таблица не объявлена'); continue; }
      var nothing = 0;
      for (i = 0; i < t.items.length; i++) {
        var it = t.items[i];
        if (!it) { bad.push(k + '[' + i + ']: пустая запись'); continue; }
        if (it.id === null || it.id === undefined) { nothing += (it.w || 0); continue; }
        checkId(k, it.id);
        if ((it.w || 0) < 0) bad.push(k + ': вес<0 у ' + it.id);
        if ((it.min || 0) > (it.max || 0)) bad.push(k + ': min>max у ' + it.id);
      }
      if (t.items.length && nothing <= 0) bad.push(k + ': нет «пусто»-слота');
    }

    // расширения — только наши добавки
    for (k in EXT) {
      if (!EXT.hasOwnProperty(k)) continue;
      if (!loot[k]) { bad.push(k + ': расширение не нашло таблицу'); continue; }
      var list = EXT[k];
      for (i = 0; i < list.length; i++) {
        if (list[i] && list[i].id) checkId('ext:' + k, list[i].id);
      }
    }
    for (k in EXT_LATE) {
      if (!EXT_LATE.hasOwnProperty(k)) continue;
      if (!loot[k]) { bad.push('late:' + k + ': таблицы так и нет'); continue; }
      var list2 = EXT_LATE[k];
      for (i = 0; i < list2.length; i++) {
        if (list2[i] && list2[i].id) checkId('late:' + k, list2[i].id);
      }
    }

    if (bad.length) {
      WS.warn('loot:tables2 self-test: ' + bad.length + ' проблем: ' + bad.join('; '));
    } else {
      WS.log('loot:tables2 self-test: OK');
    }
    return bad.length === 0;
  }

