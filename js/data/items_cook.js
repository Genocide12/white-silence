  //  items_food -> items_seed -> items_tools -> loot_tables ->
  //  recipes -> recipes_cook. Поздние слепые записи (items_food/seed)
  //  наших id не содержат — конфликтов нет; recipes.js добавляет свои
  //  fallback-предметы только на пустые места (addIfMissing).
  // ====================================================================

  WS.boot(function initItemsCook() {
    WS.Data = WS.Data || {};
    WS.Data.items = WS.Data.items || {};
    var n = 0;
    var skipped = 0;
    for (var k in items) {
      if (!items.hasOwnProperty(k)) continue;
      if (WS.Data.items[k]) {
        // не затираем чужое определение (мог загрузиться раньше)
        WS.warn('items:cook: id уже занят, пропускаю: ' + k);
        skipped++;
        continue;
      }
      WS.Data.items[k] = items[k];
      n++;
    }

    applyRu();
    if (WS.Ev && WS.Ev.on) {
      WS.Ev.on('game:start', applyRu);
      WS.Ev.on('game:load', applyRu);
    }
    if (WS.afterFirstFrame) WS.afterFirstFrame(applyRu);

    selfTest();

    WS.log('items:cook — ' + n + ' новых предметов' +
      (skipped ? ' (пропущено дублей: ' + skipped + ')' : '') +
      ', строк словаря: ' + ruCount());
  }, 'items:cook');

  WS.def('DataItemsCook', {
    items: items,
    locale: RU,
    selfTest: selfTest
  });
