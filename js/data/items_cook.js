  //  каждая цепочка cook -> указывает на существующий здесь предмет.
  // ====================================================================

  function selfTest() {
    var problems = [];
    var cats = { food: 1, drink: 1, tool: 1, container: 1 };
    var dishes = 0;
    for (var k in items) {
      if (!items.hasOwnProperty(k)) continue;
      var o = items[k];
      if (!cats[o.cat]) problems.push(k + ': cat "' + o.cat + '" не кухонный');
      if (!RU['item.' + k + '.name']) problems.push(k + ': нет имени в словаре');
      if (o.cat === 'food' || o.cat === 'drink') {
        dishes++;
        if (typeof o.cal !== 'number' || o.cal < 0 || o.cal > 2200) {
          problems.push(k + ': cal ' + o.cal + ' вне 0..2200');
        }
        if (typeof o.thir !== 'number') problems.push(k + ': нет thir');
        if (typeof o.per !== 'number') problems.push(k + ': нет per');
      }
      // цепочка cook указывает на существующий предмет?
      if (o.cook && !items[o.cook]) {
        problems.push(k + ': cook -> "' + o.cook + '" не объявлен в items_cook');
      }
    }
    if (dishes < 70) problems.push('блюд меньше 70: ' + dishes);
    if (problems.length) {
      WS.warn('items:cook self-test: ' + problems.length + ' проблем: ' + problems.join('; '));
    }
    return problems.length === 0;
  }

