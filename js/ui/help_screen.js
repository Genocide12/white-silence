  // ====================================================================
  //  ПОИСКОВЫЙ ИНДЕКС
  //  Один вход = одна «карточка» (раздел целиком). Текст карточки —
  //  заголовок + все строки/абзацы/пункты; нормализация ё→е.
  // ====================================================================

  function buildIndex() {
    if (index) return index;
    index = [];
    for (var t = 0; t < TABS.length; t++) {
      var tab = TABS[t];
      var secs = SECTIONS[tab.id] || [];
      for (var s = 0; s < secs.length; s++) {
        var sec = secs[s];
        var bag = [sec.t || ''];
        var i;
        if (sec.rows) {
          for (i = 0; i < sec.rows.length; i++) {
            bag.push(sec.rows[i][0], sec.rows[i][1]);
          }
        }
        if (sec.ps) {
          for (i = 0; i < sec.ps.length; i++) bag.push(sec.ps[i]);
        }
        if (sec.list) {
          for (i = 0; i < sec.list.length; i++) bag.push(sec.list[i]);
        }
        index.push({
          tabId: tab.id,
          tabName: tab.name,
          sec: sec,
          hay: norm(bag.join(' \u0001 '))
        });
      }
    }
    return index;
  }

  /** Поиск по нормализованной строке: массив карточек. */
  function search(q) {
    q = norm(q);
    if (!q) return null;
    var idx = buildIndex();
    var out = [];
    for (var i = 0; i < idx.length && out.length < SEARCH_MAX; i++) {
      if (idx[i].hay.indexOf(q) >= 0) out.push(idx[i]);
    }
    return out;
  }

