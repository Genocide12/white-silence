  // ====================================================================
  //  DOM
  // ====================================================================

  function buildDom() {
    if (built) return;
    var uiRoot = document.getElementById('ui-root');
    if (!uiRoot) { WS.warn('help: нет #ui-root'); return; }
    injectStyles();

    root = el('div', 'ws-panel ws-screen');
    root.id = 'ws-help';
    root.classList.add('hidden');

    // --- рамка окна -------------------------------------------------
    var frame = el('div', 'ws-frame wsh-frame', null, root);

    var head = el('div', 'scr-head', null, frame);
    el('span', 'scr-title', T('help.title', 'Справка'), head);
    var sub = el('span', 'scr-sub', '', head);
    var key = el('span', 'scr-key', 'F1', head);
    key.title = T('help.key.title', 'Клавиша справки');
    var closeBtn = el('button', 'scr-close', '\u2715', head);
    closeBtn.type = 'button';
    closeBtn.title = T('help.close.title', 'Закрыть (F1 / Esc)');

    // --- панель вкладок + поиск ------------------------------------
    var toolbar = el('div', 'wsh-toolbar', null, frame);
    var tabsBox = el('div', 'wsh-tabs', null, toolbar);

    var searchBox = el('label', 'wsh-search', null, toolbar);
    var input = el('input', '', '', searchBox);
    input.type = 'text';
    input.placeholder = T('help.search.ph', 'Поиск по справке...');
    input.id = 'ws-help-search';
    var clearBtn = el('button', 'wsh-clear', '\u2715', searchBox);
    clearBtn.type = 'button';
    clearBtn.title = T('help.search.clear', 'Очистить поиск');

    // --- тело -------------------------------------------------------
    var page = el('div', 'wsh-page', null, frame);

    // --- подвал: подсказки + переключатель обучения -----------------
    var foot = el('div', 'scr-foot', null, frame);
    var footInner = el('div', 'wsh-foot-inner', null, foot);
    el('span', '',
      T('help.foot.hint',
        'F1 / Esc — закрыть · клик по вкладке — раздел · поиск ищет по всей справке'),
      footInner);
    var tutStatus = el('span', 'wsh-tut-status', '', footInner);
    var tutBtn = el('button', 'ws-btn', '', footInner);
    tutBtn.type = 'button';
    var count = el('span', 'wsh-count', '', footInner);

    uiRoot.appendChild(root);

    dom = {
      frame: frame, sub: sub, closeBtn: closeBtn,
      tabs: tabsBox, search: input, clear: clearBtn,
      page: page, tutBtn: tutBtn, tutStatus: tutStatus, count: count
    };

    // --- события ----------------------------------------------------
    closeBtn.addEventListener('click', function () { close(); }, false);
    clearBtn.addEventListener('click', function () {
      input.value = '';
      query = '';
      renderTabs();
      renderPage();
      try { input.focus(); } catch (e) { /* пусто */ }
    }, false);
    input.addEventListener('input', function () {
      query = input.value || '';
      renderTabs();
      renderPage();
    }, false);
    input.addEventListener('keydown', function (e) {
      // Esc в поле поиска: сначала выходим из поля, окно закроет второй Esc
      if (e && e.code === 'Escape') {
        e.stopPropagation();
        try { input.blur(); } catch (er) { /* пусто */ }
        close();
      }
    }, false);
    tutBtn.addEventListener('click', function () {
      if (WS.Tutorial && WS.Tutorial.setEnabled) {
        WS.Tutorial.setEnabled(!WS.Tutorial.isEnabled());
        updateTutBtn();
      }
    }, false);

    built = true;
  }

  /** Подвал: кнопка обучения (+строка прогресса) и счётчик карточек. */
  function updateTutBtn() {
    if (!dom.tutBtn) return;
    var on = !(WS.Tutorial && WS.Tutorial.isEnabled) || WS.Tutorial.isEnabled();
    dom.tutBtn.textContent = T('help.tut.btn', 'Обучение: ') +
      (on ? T('help.tut.on', 'ВКЛ') : T('help.tut.off', 'ВЫКЛ'));
    dom.tutBtn.title = T('help.tut.btn.title',
      'Пошаговые подсказки первых часов игры (они же — в паузе)');
    if (dom.tutStatus) {
      var txt = '';
      if (WS.Tutorial && WS.Tutorial.statusText) {
        try { txt = WS.Tutorial.statusText(); } catch (e) { txt = ''; }
      }
      dom.tutStatus.textContent = txt;
    }
  }

