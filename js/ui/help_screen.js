  /** Отрисовать вкладки (подсветка активной, бейдж поиска). */
  function renderTabs() {
    if (!dom.tabs) return;
    while (dom.tabs.firstChild) dom.tabs.removeChild(dom.tabs.firstChild);
    var searching = !!query;
    for (var i = 0; i < TABS.length; i++) {
      var tab = TABS[i];
      var b = el('button', 'jr-tab' +
        (!searching && curTab === tab.id ? ' active' : ''));
      b.type = 'button';
      b.textContent = tab.name;
      (function (id) {
        b.addEventListener('click', function () {
          curTab = id;
          query = '';
          if (dom.search) dom.search.value = '';
          snd('select', 0.25);
          renderTabs();
          renderPage();
        }, false);
      })(tab.id);
      dom.tabs.appendChild(b);
    }
  }

  /** Нарисовать раздел (заголовок + таблица + список + проза). */
  function renderSection(sec, tabName) {
    var box = el('div', 'wsh-sec');

    var title = el('div', 'wsh-sec-title', sec.t || '');
    if (tabName) {
      el('span', 'wsh-badge', tabName, title);
    }
    box.appendChild(title);

    var i;
    if (sec.rows) {
      for (i = 0; i < sec.rows.length; i++) {
        var row = el('div', 'wsh-row', null, box);
        el('div', 'wsh-k', sec.rows[i][0], row);
        el('div', 'wsh-v', sec.rows[i][1], row);
      }
    }
    if (sec.list) {
      for (i = 0; i < sec.list.length; i++) {
        el('div', 'wsh-li', sec.list[i], box);
      }
    }
    if (sec.ps) {
      for (i = 0; i < sec.ps.length; i++) {
        el('div', 'wsh-p', sec.ps[i], box);
      }
    }
    return box;
  }

  /** Перерисовать страницу: вкладка или результаты поиска. */
  function renderPage() {
    if (!dom.page) return;
    var page = dom.page;
    while (page.firstChild) page.removeChild(page.firstChild);

    // --- режим поиска -----------------------------------------------
    if (query) {
      var found = search(query);
      var n = found ? found.length : 0;
      if (dom.count) {
        dom.count.textContent = T('help.search.count',
          'Найдено карточек: {n}').replace('{n}', String(n));
      }
      if (!n) {
        el('div', 'wsh-empty',
          T('help.search.empty',
            'По слову «{q}» ничего нет. Попробуйте короче: «волк», «лёд», «сон»...')
            .replace('{q}', query),
          page);
        return;
      }
      for (var i = 0; i < found.length; i++) {
        page.appendChild(renderSection(found[i].sec, found[i].tabName));
      }
      return;
    }

    // --- обычная вкладка --------------------------------------------
    if (dom.count) {
      var secs = SECTIONS[curTab] || [];
      dom.count.textContent = T('help.card.count',
        'Раздел: {t} · карточек: {n}')
        .replace('{t}', tabName(curTab)).replace('{n}', String(secs.length));
    }
    var list = SECTIONS[curTab] || [];
    for (var s = 0; s < list.length; s++) {
      page.appendChild(renderSection(list[s], null));
    }
  }

  /** Имя вкладки по id. */
  function tabName(id) {
    for (var i = 0; i < TABS.length; i++) {
      if (TABS[i].id === id) return TABS[i].name;
    }
    return '';
  }

  /** Подзаголовок окна. */
  function updateSub() {
    if (!dom.sub) return;
    var s = tabName(curTab);
    if (query) {
      s = T('help.sub.search', 'Поиск') + ': «' + query + '»';
    }
    dom.sub.textContent = s;
  }

  // ====================================================================
  //  ОТКРЫТИЕ / ЗАКРЫТИЕ
  // ====================================================================

  /** Открыть справку (tabId — необязательная вкладка). Через реестр
   *  WS.Ui — тогда стек модальных окон честен и Esc ядра закрывает
   *  нас первым (closeTop), а не паузит игру поверх справки. */
  function openHelp(tabId) {
    buildDom();
    if (!root) return;

    // уже открыто: просто перелистнуть вкладку/очистить поиск
    if (isOpen) {
      if (tabId && tabId !== curTab) {
        curTab = tabId;
        query = '';
        if (dom.search) dom.search.value = '';
      }
      renderTabs();
      renderPage();
      updateSub();
      return;
    }

    if (tabId && SECTIONS[tabId]) curTab = tabId;

    // 1) реестр: классы + стек (open зарегистрирован как null — без
    //    обратного вызова, состоянием владеем мы сами)
    var viaUi = false;
    if (WS.Ui && WS.Ui.open) {
      try { viaUi = WS.Ui.open('help'); } catch (e) { viaUi = false; }
    }
    if (!viaUi) {
      root.classList.remove('hidden');
      root.classList.add('ws-modal');
    }

    // 2) своё состояние и рендер
    isOpen = true;
    updateTutBtn();
    renderTabs();
    renderPage();
    updateSub();
    snd('door', 0.25);
    try { WS.Ev.emit('ui:screen', { id: 'help', open: true }); } catch (e2) { /* пусто */ }
  }

  /** Ручное закрытие (без реестра) — только классы и состояние. */
  function manualClose() {
    isOpen = false;
    if (root) {
      root.classList.add('hidden');
      root.classList.remove('ws-modal');
    }
  }

  /** Закрыть. Если есть реестр — идём через него, чтобы вынуться и из
   *  стека (иначе Ui.modal() видел бы нас навсегда). */
  function close() {
    if (!isOpen) return;
    if (WS.Ui && WS.Ui.close) {
      try { WS.Ui.close('help'); return; } catch (e) { /* ниже — вручную */ }
    }
    manualClose();
    snd('door', 0.2);
    try { WS.Ev.emit('ui:screen', { id: 'help', open: false }); } catch (e2) { /* пусто */ }
  }

  /** Внутреннее закрытие для реестра: Ui.close сам снимет классы и стек,
   *  от нас требуется только состояние, звук и событие. */
  function closeFromUi() {
    if (!isOpen) return;
    manualClose();
    snd('door', 0.2);
    try { WS.Ev.emit('ui:screen', { id: 'help', open: false }); } catch (e) { /* пусто */ }
  }

  function toggle(tabId) {
    if (isOpen) close();
    else openHelp(tabId);
  }

  /** Звук (громкость по умолчанию тихая — справка не событие). */
  function snd(name, vol) {
    if (WS.Snd && WS.Snd.play) {
      try { WS.Snd.play(name, { vol: vol == null ? 0.3 : vol }); } catch (e) { /* пусто */ }
    }
  }

  // ====================================================================
  //  КЛАВИАТУРА: F1 — всегда (и в поле поиска), Esc из поля — тоже.
  //  Основной Esc ловит ядро UI (stack), нам остаётся страховка.
  // ====================================================================

  function onKey(e) {
    if (!e || e.repeat) return;
    var tag = (e.target && e.target.tagName) || '';
    var inField = (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT');

    if (e.code === KEY_CODE) {
      // F1 не должен открывать справку браузера — гасим действие
      try { e.preventDefault(); } catch (er) { /* пусто */ }
      toggle();
      return;
    }
    if (e.code === 'Escape' && isOpen && inField) {
      // из поля поиска Esc должен закрыть окно, а не потеряться
      try { e.preventDefault(); } catch (er2) { /* пусто */ }
      close();
    }
  }

  // ====================================================================
  //  САМОДИАГНОСТИКА (консоль: WS.Help.selftest())
  // ====================================================================

  function selftest() {
    var out = [];
    var pass = 0, fail = 0;
    function ok(name, cond) {
      if (cond) { pass++; out.push('  ok   ' + name); }
      else { fail++; out.push('  FAIL ' + name); }
      return !!cond;
    }

    ok('модуль зарегистрирован (WS.Help)', !!WS.Help);
    ok('вкладок шесть', TABS.length === 6);
    ok('порядок вкладок: управление→советы', (function () {
      return TABS[0].id === 'controls' && TABS[5].id === 'tips';
    })());
    ok('у каждой вкладки есть разделы', (function () {
      for (var i = 0; i < TABS.length; i++) {
        var s = SECTIONS[TABS[i].id];
        if (!s || !s.length) return false;
      }
      return true;
    })());
    ok('в «Управлении» перечислены E, I, C, B, Z, Пробел', (function () {
      var rows = SECTIONS.controls[0].rows;
      var have = {};
      for (var i = 0; i < rows.length; i++) have[rows[i][0]] = 1;
      return !!(have['E'] && (have['I / Tab']) && have['C'] && have['B'] &&
                have['Z'] && have['Пробел']);
    })());
    ok('в «Советах» ровно 20 правил', (function () {
      return SECTIONS.tips[0].rows.length === 20;
    })());
    ok('упомянуты полярная ночь (44) и пароход (60)', (function () {
      var idx = buildIndex();
      var polar = false, ship = false;
      for (var i = 0; i < idx.length; i++) {
        if (idx[i].tabId === 'world') {
          if (idx[i].hay.indexOf('44') >= 0) polar = true;
          if (idx[i].hay.indexOf('60') >= 0) ship = true;
        }
      }
      return polar && ship;
    })());
    ok('поиск «волк» находит зверей', (function () {
      var r = search('волк') || [];
      return r.length >= 2;
    })());
    ok('поиск «ё» нормализуется (ёж→еж)', norm('Ёлка, ёж') === 'елка, еж');
    ok('пустой запрос — не поиск', search('') === null);
    ok('окно закрыто вне открытия', isOpen === false);

    out.push('  --   итог: ' + pass + ' ок, ' + fail + ' провал');
    return out;
  }

