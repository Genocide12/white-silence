  var shown = false;

  /** Экран загрузки: показывает советы и скрывает себя. */
  function show(duration, tip) {
    if (shown) return;
    shown = true;
    var root = document.getElementById('ui-root');
    if (!root) return;

    var wrap = document.createElement('div');
    wrap.id = 'ws-loading';
    wrap.className = 'ws-loading';

    var inner = document.createElement('div');
    inner.className = 'ws-loading-inner';

    var title = document.createElement('div');
    title.className = 'ws-loading-title';
    title.textContent = 'БЕЛОЕ БЕЗМОЛВИЕ';

    var bar = document.createElement('div');
    bar.className = 'ws-loading-bar';
    var fill = document.createElement('div');
    fill.className = 'ws-loading-fill';
    bar.appendChild(fill);

    var tipEl = document.createElement('div');
    tipEl.className = 'ws-loading-tip';
    tipEl.textContent = tip || TIPS[Math.floor(Math.random() * TIPS.length)];

    inner.appendChild(title);
    inner.appendChild(bar);
    inner.appendChild(tipEl);
    wrap.appendChild(inner);
    root.appendChild(wrap);

    // анимация прогресса
    var t0 = performance.now();
    var dur = duration || 1600;
    function step() {
      var p = Math.min(1, (performance.now() - t0) / dur);
      fill.style.width = (p * 100).toFixed(1) + '%';
      if (p < 1) {
        requestAnimationFrame(step);
      } else {
        setTimeout(function () {
          wrap.classList.add('ws-loading-out');
          setTimeout(function () {
            if (wrap.parentNode) wrap.parentNode.removeChild(wrap);
            shown = false;
          }, 600);
        }, 350);
      }
    }
    requestAnimationFrame(step);
  }

  /** Интерлюдия акта: полноэкранная фраза на 3 секунды. */
  function interlude(day) {
    var text = INTERLUDES[day];
    if (!text) return;
    var root = document.getElementById('ui-root');
    if (!root) return;
    var el = document.createElement('div');
    el.className = 'ws-interlude';
    el.textContent = text;
    root.appendChild(el);
    setTimeout(function () {
      el.classList.add('ws-interlude-out');
      setTimeout(function () {
        if (el.parentNode) el.parentNode.removeChild(el);
      }, 1200);
    }, 2600);
  }

  WS.boot(function initLoading() {
    // при старте партии — экран загрузки
    WS.Ev.on('game:start', function () {
      show(1400);
    });
    WS.Ev.on('game:load', function () {
      show(900, 'Партия продолжается. Снег помнит ваше отсутствие.');
    });
    // интерлюдии по дням
    WS.Ev.on('time:day', function (d) {
      if (d && d.day && INTERLUDES[d.day] && WS.G && WS.G.running) {
        interlude(d.day);
      }
    });
  }, 'loading:init');

  WS.def('Loading', {
    show: show,
    interlude: interlude,
    tips: TIPS,
    randomTip: function () { return TIPS[Math.floor(Math.random() * TIPS.length)]; }
  });
