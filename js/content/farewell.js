/**
 * ПРОЩАЛЬНЫЕ СЛОВА: надписи на стенах, найденные записки-финалы,
 * и «что стало с ними потом» — эпилоги для экрана победы.
 */
(function () {
  'use strict';

  // ================================================================ ЭПИЛОГИ ПОБЕДЫ
  var EPILOGUES = [
    'В судовой роли парохода «Святой Николай» появится строка: «один пассажир, с места происшествия». Кормщик потом расскажет, что вы молчали всю дорогу и улыбались пароходному теплу, как улыбаются чужому доброму дому.',
    'В Мезени вас спросят: «Как там, на Пристани?» Вы будете думать, что отвечать, весь следующий год.',
    'Шкипер Ковалёв выпьет с вами за упокой тех, кто не дождался. И за здравие тех, кто ещё ждёт — где-то.',
    'Весной, когда река вскроется, на пристань зайдёт первый караван барж. Спросят: «Жив кто?» И баржевой старшина запишет в книгу: «Пусто. Один ушёл до нас».',
    'Вы будете иногда просыпаться от тишины и искать печь. Печь будет рядом — но уже не ваша, и это, если честно, к лучшему.'
  ];

  // ================================================================ НАДПИСИ НА СТЕНАХ
  var WALL_WRITINGS = [
    'Углём на бревне: «Мы ушли к устью. Догоняй. 1914».',
    'На створе двери ножом: «Здесь был Степка. Все ок».',
    'На полях счётной книги: «Считать больше нечего — считаю дни».',
    'На печном кирпиче: «Топи, кто остался. Не жалей дров. — М.».',
    'На окне изнутри, пальцем по пыли: «Света нет. Ушли на север».',
    'На столешнице глубокой резьбой: «СТОЙ. ДЫШИ. ДАЛЬШЕ.»',
    'На притолоке: «Прошу Бога: пусть найдётся кто живой».',
    'На полене: «Денис дурак. Всё равно ушёл».',
    'На подоконнике: «Ждём пароход. Ждём пароход. Ждём».',
    'На дверце шкафа: «Одежда Марьи. Марья ушла. Одежда осталась.»'
  ];

  // ================================================================ ПОСЛЕДНИЕ СЛОВА (радио-обрывки)
  var LAST_WORDS = [
    '«...передайте жене...» (далее помехи)',
    '«...ставка пала, повторяю, став...»',
    '«...мы держимся, но недолго...»',
    '«...если это слышит кто-то из наших — мы у Зимней станции...»',
    '«...не ищите нас...»',
    '«...пусть кто-нибудь знает: мы были».'
  ];

  function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }

  /** Эпилог для победы. */
  function epilogue() { return pick(EPILOGUES); }

  /** Случайная надпись на стене (для обысков). */
  function wallWriting() { return pick(WALL_WRITINGS); }

  /** Обрывок радиоперехвата. */
  function lastWord() { return pick(LAST_WORDS); }

  /** Показать надпись при обыске контейнера (шанс). */
  WS.boot(function initFarewell() {
    WS.Ev.on('loot:searched', function (d) {
      if (!d || !d.o || !WS.G || !WS.G.running) return;
      if (Math.random() > 0.06) return;   // редкий шанс
      var text = wallWriting();
      if (WS.Ui && WS.Ui.toast) {
        WS.Ui.toast('На стенах находишь надпись: ' + text, 'info');
      }
      if (WS.G.player) {
        WS.G.player.needs.sanity = Math.min(100, WS.G.player.needs.sanity + 1);
      }
      if (WS.G.story && WS.G.story.chronicle) {
        WS.G.story.chronicle.push({ day: WS.Time.day(), text: 'Надпись: ' + text.slice(0, 40) });
      }
    });

    // эпилог при победе
    WS.Ev.on('game:victory', function () {
      if (WS.G && WS.G.story && WS.G.story.chronicle) {
        WS.G.story.chronicle.push({ day: WS.Time.day(), text: 'ЭПИЛОГ: ' + epilogue().slice(0, 60) });
      }
    });
  }, 'farewell:init');

  WS.def('Farewell', {
    epilogue: epilogue,
    wallWriting: wallWriting,
    lastWord: lastWord,
    EPILOGUES: EPILOGUES,
    WALL_WRITINGS: WALL_WRITINGS,
    LAST_WORDS: LAST_WORDS
  });
})();
