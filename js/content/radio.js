  /** Кандидаты: день в окне, час совпал, ещё не звучало. */
  function candidates(d, h) {
    var out = [];
    for (var i = 0; i < B.length; i++) {
      var bc = B[i];
      if (d < bc.day_min || d > bc.day_max) continue;
      if (bc.hour !== h) continue;
      if (played(bc.id)) continue;
      out.push(bc);
    }
    return out;
  }

  /** Самый приоритетный кандидат (при равенстве — случайный из равных). */
  function pickBest(list) {
    if (!list.length) return null;
    var best = list[0];
    var same = [list[0]];
    for (var i = 1; i < list.length; i++) {
      if (list[i].prio > best.prio) { best = list[i]; same = [list[i]]; }
      else if (list[i].prio === best.prio) { same.push(list[i]); }
    }
    return same[Math.floor(Math.random() * same.length)];
  }

