  function ensureDom() {
    if (st.dom) return true;
    var uiRoot = document.getElementById('ui-root');
    if (!uiRoot) return false;
    try {
      var style = document.getElementById('ws-radio-style');
      if (!style) {
        style = document.createElement('style');
        style.id = 'ws-radio-style';
        style.textContent = BAND_CSS;
        document.head.appendChild(style);
      }
      var root = document.createElement('div');
      root.id = 'ws-radio-band';
      root.innerHTML =
        '<div class="rb-head"><span class="rb-name">Эфир</span>' +
        '<span style="display:flex;align-items:center;">' +
        '<span class="rb-vu"><i></i><i></i><i></i><i></i><i></i></span>' +
        '<span class="rb-freq"></span></span></div>' +
        '<div class="rb-text"></div>';
      uiRoot.appendChild(root);
      st.dom = {
        root: root,
        freq: root.querySelector('.rb-freq'),
        text: root.querySelector('.rb-text'),
        vu: root.querySelectorAll('.rb-vu i')
      };
      return true;
    } catch (e) {
      WS.err('radio: лента недоступна', e && e.message);
      st.dom = null;
      return false;
    }
  }

  /** Показать передачу в ленте (машинка печатает ~46 знаков в секунду). */
  function showBand(text, freq) {
    if (!ensureDom() || !st.dom) return;
    st.dom.freq.textContent = freq || FREQ_MAIN;
    st.dom.root.classList.add('on');
    st.band = { text: String(text), shown: 0, t: 0, hold: 0 };
    renderBand();
  }

  function renderBand() {
    if (!st.dom || !st.band) return;
    var b = st.band;
    var shown = b.text.slice(0, Math.floor(b.shown));
    var done = b.shown >= b.text.length;
    st.dom.text.textContent = shown + (done ? '' : ' ');
    // курсор-каретка на время печати
    st.dom.text.innerHTML = '';
    st.dom.text.appendChild(document.createTextNode(shown));
    if (!done) {
      var cur = document.createElement('span');
      cur.className = 'rb-cur';
      st.dom.text.appendChild(cur);
    }
  }

  /** «Игла громкости»: столбики дёргаются, пока машинка печатает. */
  function vuTick() {
    if (!st.dom || !st.dom.vu || !st.band) return;
    var printing = st.band.shown < st.band.text.length;
    for (var i = 0; i < st.dom.vu.length; i++) {
      var h = printing ? (2 + Math.random() * 10) : (2 + Math.random() * 3);
      st.dom.vu[i].style.height = Math.round(h) + 'px';
    }
  }

  function hideBand() {
    if (st.dom && st.dom.root) st.dom.root.classList.remove('on');
    st.band = null;
  }

  /** Тик ленты: печатная машинка + игла + удержание + скрытие. */
  function bandTick(dt) {
    // раз в ~5 секунд: не зашёл ли игрок в контору без приёмника
    st.hintT = (st.hintT || 0) + dt;
    if (st.hintT > 5) {
      st.hintT = 0;
      try { onEnterStation(); } catch (e2) { /* подсказка не критична */ }
    }
    if (!st.band) return;
    var b = st.band;
    b.t += dt;
    if (b.t > 0.08) { b.t = 0; vuTick(); }        // игла — 12 Гц, не чаще
    if (b.shown < b.text.length) {
      b.shown += TYPE_SPEED * dt;
      if (b.shown > b.text.length) b.shown = b.text.length;
      renderBand();
      return;
    }
    b.hold += dt;
    if (b.hold >= BAND_HOLD) hideBand();
  }

  // ====================================================================
  //  ПЕРЕДАЧИ ОТ STORY.JS: transmit(id, text)
  //  Сюжет (E1) делает тост/хронику/звук сам — мы оформляем: лента
  //  «в эфире», запись в журнал и флаг слышанности.
  // ====================================================================

  function transmit(id, text) {
    if (!text) return;
    var key = 'story_' + (id || 'x');
    fs('rad_' + key, 1);
    logMessage({ text: String(text), freq: FREQ_STORY });
    showBand(String(text), FREQ_STORY);
    st.inited = true;
  }

  // ====================================================================
  //  ПУБЛИЧНОЕ ЧТЕНИЕ СОСТОЯНИЯ ЭФИРА (для журнала и соседей)
  // ====================================================================

  /** Лента услышанного (новые сверху — журнал сам переворачивает). */
  function messages() {
    return st.messages.slice();
  }

  /**
   * Строка состояния эфира — журнал показывает её, пока лента пуста.
   * Без приёмника — «ручка крутится впустую», в полярную ночь — треск.
   */
  function status() {
    var g = WS.G;
    if (!g || !g.running) return 'эфир существует и без вас';
    var d = day();
    if (!canHear()) {
      return 'приёмника при вас нет — эфир идёт мимо ушей';
    }
    if (d <= 14) return 'эфир живой: сводки, метео, цены';
    if (d <= 30) return 'эфир тревожный: станции путаются в показаниях';
    if (d <= 43) return 'эфир редеет: слова всё короче, треск всё длиннее';
    return 'эфир молчит — один треск, и в треске не всегда есть слово';
  }

  /**
   * Расписание волны на день: что и во сколько можно услышать
   * (отладка и соседние модули — например, чтоб пометить на карте
   * «радиочас»). Возвращает [{hour, id, kind, heard}].
   */
  function schedule(d0) {
    var d = (typeof d0 === 'number') ? d0 : day();
    var out = [];
    for (var i = 0; i < B.length; i++) {
      var bc = B[i];
      if (d < bc.day_min || d > bc.day_max) continue;
      out.push({ hour: bc.hour, id: bc.id, kind: bc.kind, heard: !!played(bc.id) });
    }
    if (d <= 43) {
      out.push({ hour: METEO_HOUR, id: 'reg_m', kind: 'meteo',
                 heard: !!fg('rad_reg_m_' + d) });
      out.push({ hour: PRICE_HOUR, id: 'reg_p', kind: 'price',
                 heard: !!fg('rad_reg_p_' + d) });
    }
    out.sort(function (a, b) { return a.hour - b.hour; });
    return out;
  }

  /** Сколько передач услышано за партию (сюжетные — в счёт). */
  function heardCount() {
    var n = st.messages.length;
    return n;
  }

  /** Восстановление ленты после загрузки сейва. */
  function reattach() {
    var s = F();
    st.messages = [];
    if (s && s.radio && s.radio.length) {
      for (var i = 0; i < s.radio.length; i++) {
        if (s.radio[i] && s.radio[i].text) st.messages.push(s.radio[i]);
      }
    }
    st.band = null;
    hideBand();
    st.inited = true;
  }

  /** Новая партия: эфир с чистого листа. */
  function newGame() {
    st.messages = [];
    st.band = null;
    hideBand();
    st.inited = true;
  }

  // ====================================================================
  //  ПОДСКАЗКИ О ПРИЁМНИКЕ (одноразовые, вежливые)
  //  Первая — когда кристалл впервые оказывается в сумке; вторая —
  //  когда игрок без приёмника заходит в контору вокзала.
  // ====================================================================

  function onItemPicked(d) {
    var id = d && d.id;
    if (id !== 'radio_crystal') return;
    if (fg('rad_hint_pickup')) return;
    fs('rad_hint_pickup', 1);
    toast('Кристаллический приёмник при вас. Теперь передачи слышно и не из конторы.', 'good');
    chron('Найден кристаллический приёмник: эфир теперь ходит за вами.', 'find');
  }

  function onEnterStation() {
    if (fg('rad_hint_station') || fg('rad_hint_pickup')) return;
    if (!inStation()) return;
    fs('rad_hint_station', 1);
    toast('Стол конторы помнит аппараты: у стены ещё один приёмник, чинный и тяжёлый.', 'info');
  }

  // ====================================================================
  //  САМОТЕСТ (консоль: WS.Radio.selftest())
  // ====================================================================

  function selftest() {
    var out = [];
    var ok = function (name, cond) {
      out.push((cond ? '  ok  ' : ' FAIL ') + name);
      return !!cond;
    };
    ok('передач в таблице: 40', B.length === 40);
    ok('все передачи с текстом', (function () {
      for (var i = 0; i < B.length; i++) if (!B[i].text) return false;
      return true;
    })());
    ok('все id уникальны', (function () {
      var seen = {};
      for (var i = 0; i < B.length; i++) {
        if (seen[B[i].id]) return false;
        seen[B[i].id] = 1;
      }
      return true;
    })());
    ok('часа в разумных рамках', (function () {
      for (var i = 0; i < B.length; i++) {
        if (B[i].hour < 0 || B[i].hour > 23) return false;
      }
      return true;
    })());
    ok('окна дней не задраны за 59', (function () {
      for (var i = 0; i < B.length; i++) {
        if (B[i].day_min < 1 || B[i].day_max > 59) return false;
      }
      return true;
    })());
    ok('надежда про пароход в днях 55+', (function () {
      for (var i = 0; i < B.length; i++) {
        if (B[i].kind === 'hope') return B[i].day_min >= 55;
      }
      return false;
    })());
    ok('дни 1-10 без обрывков', (function () {
      for (var i = 0; i < B.length; i++) {
        if (B[i].day_max <= 10 &&
            (B[i].kind === 'frag' || B[i].kind === 'sos' || B[i].kind === 'static')) {
          return false;
        }
      }
      return true;
    })());
    ok('метео-текст собирается', meteoText().indexOf('Мороз') > 0);
    ok('цены собираются', (function () {
      // просто проверяем, что функция не падает на любом дне
      priceText();
      return true;
    })());
    ok('статика не пуста', STATIC_POOL.length >= 8);
    ok('слухи по эфиру есть', RUMOR_POOL.length >= 12);
    ok('tryPlay без партии молчит', (function () {
      var g = WS.G;
      if (!g || !g.running) return true;               // партии нет — и ладно
      return typeof tryPlay(day(), hour()) === 'boolean';
    })());
    ok('status() даёт строку', typeof status() === 'string' && status().length > 3);
    out.unshift('radio.selftest: пройдено');
    return out;
  }

