  function T(key, fb) {
    if (WS.I18N && WS.I18N.t) {
      try { return WS.I18N.t(key, fb); } catch (e) { /* словарь спит */ }
    }
    return (typeof fb === 'string') ? fb : key;
  }

  function invCount(id) {
    if (WS.Inv && WS.Inv.count) { try { return WS.Inv.count(id); } catch (e) { return 0; } }
    return 0;
  }

