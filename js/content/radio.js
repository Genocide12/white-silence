  /** Игрок в здании вокзала (type 'telegraph')? */
  function inStation() {
    var p = P();
    var w = WS.World;
    if (!p || !w || !w.buildings) return false;
    for (var i = 0; i < w.buildings.length; i++) {
      var b = w.buildings[i];
      if (b && b.type === 'telegraph' &&
          p.x >= b.x && p.x < b.x + b.w && p.y >= b.y && p.y < b.y + b.h) {
        return true;
      }
    }
    return false;
  }

