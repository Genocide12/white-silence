  function P() { var g = WS.G; return (g && g.player) ? g.player : null; }

  /** Сюжетное хранилище с гарантированными полями. */
  function F() {
    var g = WS.G;
    var s = g && g.story;
    if (!s) {
      if (!g) return null;
      s = g.story = { notes: [], radio: [], flags: {}, hints: {} };
    }
    if (!s.flags) s.flags = {};
    if (!s.radio || !s.radio.push) s.radio = [];
    if (!s.chronicle || !s.chronicle.push) s.chronicle = [];
    return s;
  }

  function fg(n) { var s = F(); return s ? s.flags[n] : undefined; }
  function fs(n, v) { var s = F(); if (s) s.flags[n] = (v === undefined ? 1 : v); }

  function day() { return (WS.Time && WS.Time.day) ? WS.Time.day() : 1; }
  function hour() { return (WS.Time && WS.Time.hour) ? WS.Time.hour() : 8; }

  function timeShort() {
    try {
      var h = WS.Time.hour(), m = WS.Time.minute();
      return (h < 10 ? '0' : '') + h + ':' + (m < 10 ? '0' : '') + m;
    } catch (e) { return ''; }
  }

  function clamp(v, lo, hi) { return v < lo ? lo : (v > hi ? hi : v); }

  function toast(text, kind) {
    if (!text) return;
    if (WS.Ui && WS.Ui.toast) {
      try { WS.Ui.toast(text, kind || 'info'); return; } catch (e) { /* молча */ }
    }
    try { WS.Ev.emit('ui:toast', { text: text, kind: kind || 'info' }); } catch (e2) { /* пусто */ }
  }

  function snd(name, vol) {
    try {
      var p = P();
      var o = { vol: vol === undefined ? 0.85 : vol };
      if (p) { o.x = p.x; o.y = p.y; }
      if (WS.Snd && WS.Snd.play) WS.Snd.play(name, o);
    } catch (e) { /* эфир без звука — всё ещё эфир */ }
  }

  /** Хроника: «Радио: » + первые 60 знаков (формат задачи E2b). */
  function chron(text, cls) {
    var s = F();
    if (!s || !text) return;
    var t = String(text);
    var cut = t.slice(0, 60) + (t.length > 60 ? '…' : '');
    s.chronicle.push({ day: day(), time: timeShort(), text: 'Радио: ' + cut, cls: cls || '' });
    while (s.chronicle.length > 100) s.chronicle.shift();
  }

