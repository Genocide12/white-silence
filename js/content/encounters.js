/**
 * ВСТРЕЧИ И НАХОДКИ: атмосферные описания при обнаружении мест и вещей.
 * Каждый тип находки — 5-8 вариантов живого текста. Не тост-спам, а подписи мира.
 */
(function () {
  'use strict';

  var E = {};

  function add(cat, arr) { E[cat] = arr; }

  // ================================================================ ПЕРВЫЙ ВХОД В ДОМ
  add('house_enter', [
    'Изба встречает вас запахом остывшей печи. Здесь жили — и уходили в спешке.',
    'Половица вздрагивает под ногой. Пыль осела недавно: след ещё не засыпан.',
    'В сенях висит чужой тулуп. Хозяину он больше не нужен — вы это уже знаете.',
    'Стол накрыт к ужину, который не случился. Тарелка под окошком, ложка поперёк.',
    'Иконы в красном углу. Стеклянная дверца приоткрыта, как будто за кем-то.',
    'Дом дышит, как дышит всё, что недавно было тёплым.'
  ]);

  // ================================================================ НАХОДИШЬ ТРУП ЖИВОТНОГО
  add('corpse_animal', [
    'Тёплое ещё. Снег вокруг примят и взрыхлён.',
    'Следов борьбы нет: зверь пришёл умирать сюда сам.',
    'Вороньё уже сказало соседям. У вас есть час, до темноты.',
    'Шкура цела — если не считать того, что случилось с сердцем.'
  ]);

  // ================================================================ НАХОДИШЬ ТРУП ЧЕЛОВЕКА
  add('corpse_human', [
    'Он сидит у стены, будто прилёг отдохнуть. Мороз сделал остальное.',
    'В кулаке — платок с инициалами. Вы его не знали. Теперь — знаете.',
    'Лицо спокойное. Так уходят те, кто успел всё понять.',
    'Сапоги целы. Кто-то уже проверял — но не снял. Странная совесть у этого леса.',
    'Рядом — четверть хлеба. Знать бы, чего в этой зиме не хватило больше: еды или воли.'
  ]);

  // ================================================================ ЗАБРОШЕННАЯ БАНЯ
  add('banya_find', [
    'Парная стоит с приоткрытой дверью: последний пар ушёл в лес вместе с людьми.',
    'В предбаннике — веники, слипшиеся от сырости. Пахнет берёзой и забвением.',
    'Печь холодная, но труба цела. Растопить — и этот угол мира снова станет живым.'
  ]);

  // ================================================================ ЦЕРКОВЬ
  add('church_enter', [
    'Свечи оплыли до подсвечников. Кто-то уходил в темноте, не оглядываясь на алтарь.',
    'Храм держит тишину так, как держат воду ладонями: бережно и недолго.',
    'На аналое — раскрытая книга. Пыль легла на строки, но буквы ещё угадываются.',
    'Вас встречает не Бог — вас встречает холод. Но в этот раз — с уважением.'
  ]);

  // ================================================================ КЛАДБИЩЕ
  add('graveyard', [
    'Кресты стоят неровно, как очередь на остановке. Снег сравнял живых и записанных.',
    'Чьё-то имя нацарапано ножом поверх выцветшего. Пока вы шли сюда, кто-то тоже ходил.',
    'Вороны на ограде ждут не вас. Но терять им нечего — и они это знают.'
  ]);

  // ================================================================ ЛЕГОВО ВОЛКОВ (найдено место)
  add('wolf_den', [
    'Снег утоптан до земли. Кострище волчьего отдыха — тёплое ещё?',
    'Здесь их спальное место: тёплый выдох земли, примятая шерсть, кости.',
    'Стая живёт здесь давно. Значит, обходить надо было ещё вчера.'
  ]);

  // ================================================================ МЕДВЕЖЬЕ ЛОГОВО (пустое)
  add('bear_den', [
    'Логово пусто, но запах стоит такой, что деревья за него держатся.',
    'Снег разворочен когтями — изнутри. Он не спит. Он просто ушёл.',
    'Следы уходят к посёлку. Это не к добру и не к вам — просто не к добру.'
  ]);

  // ================================================================ РАЗГРАБЛЕННЫЙ СКЛАД
  add('looted_store', [
    'Полки смяты в спешке: брали громкое и тёплое, мелкое топтали.',
    'Кто-то жёг факелами прямо здесь: копоть на потолке вечнее товара.',
    'На полу — счёты. Костяшки сбиты, итог не сходится. Как и везде теперь.'
  ]);

  // ================================================================ СХРОН ЕГЕРЯ
  add('ranger_cache', [
    'Под слоем хвои — аккуратно накрытый ящик. Кто-то готовился к худшему.',
    'Схрон устроен по науке: сухо, темно, от мышей — полынью. Профессионал.',
    'Здесь всё ещё верят, что хозяин вернётся. Судя по датам — не вернулся.'
  ]);

  // ================================================================ ПРИСТАНЬ
  add('pier', [
    'Мостки скрипят под весом одного человека. Второй им не нужен.',
    'Вода подо льдом черна и спокойна, как несказанное слово.',
    'Здесь вы будете стоять в конце. Если будете.',
    'Кнехты, канаты, запах смолы. Всё ждёт корабль, который ждёт воды.'
  ]);

  // ================================================================ ПОЛЯРНАЯ НОЧЬ НАСТУПИЛА
  add('polar_first', [
    'Солнце не встанет больше до самого парохода. Небо держит вас в объятьях из темноты.',
    'День и ночь слились в сумрак. Часы теперь врут по-честному.',
    'С этого часа свет — только ваш и только если вы его зажгли.'
  ]);

  // ================================================================ ПЕРВЫЙ СНЕГ СИЛЬНЫЙ
  add('blizzard_first', [
    'Метель пришла по-хозяйски: сначала заняв горизонт, потом — весь мир.',
    'Ветер не свистит — говорит. Слушать его можно только не отрываясь от стены.'
  ]);

  // ================================================================ ФАКТЫ НАХОДКИ (предмет)
  var ITEM_FOUND = [
    'На дне — то, что искали. Или то, что само искало вас.',
    'Пальцы находят раньше глаз. Глаза соглашаются позже.',
    'Завёрнуто в тряпицу — берегли. Значит, и вам беречь.',
    'Просто лежало и ждало. Как всё в этом посёлке.'
  ];

  function pick(cat) {
    var arr = E[cat];
    if (!arr || !arr.length) return '';
    return arr[Math.floor(Math.random() * arr.length)];
  }

  function maybeShow(cat, chance) {
    if (Math.random() > (chance !== undefined ? chance : 0.6)) return;
    var text = pick(cat);
    if (!text) return;
    if (WS.Ui && WS.Ui.toast) WS.Ui.toast(text, 'info');
    else if (WS.Fx && WS.G) WS.Fx.text(text.slice(0, 60), WS.G.player.x, WS.G.player.y - 1, { life: 3 });
    if (WS.G && WS.G.story && WS.G.story.chronicle) {
      WS.G.story.chronicle.push({ day: WS.Time.day(), text: text.slice(0, 50) });
    }
  }

  // ================================================================ ХУКИ
  var seen = {};
  function once(key, cat) {
    if (seen[key]) return;
    seen[key] = true;
    maybeShow(cat, 1.0);
  }

  WS.boot(function initEncounters() {
    // первый вход в дом: отслеживаем переход «снаружи → внутри»
    var wasInside = false;
    WS.tick(49, function encTick() {
      if (!WS.G || !WS.G.running || !WS.G.player) return;
      var inside = WS.World.isInside(WS.G.player.x, WS.G.player.y);
      if (inside && !wasInside) {
        var b = WS.World.buildingAt(Math.floor(WS.G.player.x), Math.floor(WS.G.player.y));
        if (b) {
          var key = 'b_' + (b.id || (b.x + ',' + b.y));
          if (/banya/.test(b.type || '')) once(key + '_b', 'banya_find');
          else if (/church/.test(b.type || '')) once(key + '_c', 'church_enter');
          else once(key, 'house_enter');
        }
      }
      wasInside = inside;
    }, 'enc:tick');

    // находки-события
    WS.Ev.on('loot:searched', function (d) {
      if (!d || !d.o) return;
      if (d.count > 0 && Math.random() < 0.35 && WS.Fx && WS.G) {
        WS.Fx.text(pick('item_find') || '', d.o.x, d.o.y - 0.6, { life: 2.2, col: '#9db0c8' });
      }
    });

    // трупы
    WS.Ev.on('ent:kill', function (d) {
      if (!d || !d.ent) return;
      if (d.ent.kind === 'bandit') setTimeout(function () { maybeShow('corpse_human', 0.8); }, 400);
      else if (d.ent.hp !== undefined) setTimeout(function () { maybeShow('corpse_animal', 0.5); }, 400);
    });

    // полярная ночь
    WS.Ev.on('time:day', function (d) {
      if (d && d.day === 44) maybeShow('polar_first', 1.0);
    });

    // первая метель
    WS.Ev.on('weather:changed', function (d) {
      if (d && d.to === 'blizzard' && !seen.blizzard) {
        seen.blizzard = true;
        maybeShow('blizzard_first', 1.0);
      }
    });
  }, 'encounters:init');

  WS.def('Encounters', {
    pick: pick,
    maybeShow: maybeShow,
    ITEM_FOUND: ITEM_FOUND
  });
})();
