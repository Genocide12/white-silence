  function flags() { return (WS.G && WS.G.story && WS.G.story.flags) || {}; }
  function stat(id) { return (WS.G && WS.G.stats && WS.G.stats[id]) || 0; }

  function determineEnding(cause) {
    // смерть под сиянием?
    if (cause === 'aurora') return ENDINGS.aurora;
    // победа с семейством?
    if (flags().child_saved && flags().semen_alive && flags().horse_saved) return ENDINGS.family;
    // схимник: остался с Акимом
    if (flags().stay_with_akim) return ENDINGS.schemnik;
    // атаман: все бандиты истреблены + поздняя игра
    if (flags().all_bandits_dead && WS.Time.day() >= 50) return ENDINGS.ataman;
    // волчий царь
    if (stat('wolvesKilled') >= 100) return ENDINGS.wolf_king;
    // пароход: сигнальный огонь
    if (flags().signal_fire_lit) return ENDINGS.ship;
    // зимовка: дожил до конца без огня
    if (WS.Time.day() >= WS.Time.DAYS_TO_SHIP) return ENDINGS.wintering;
    // обычная смерть
    return null;
  }

  // ================================================================ ПОКАЗ
  function show(ending, cause) {
    if (!ending) return false;
    if (WS.G) WS.G.deathEpitaph = ending;
    var full = ending.title + '\n\n' + ending.text + '\n\n' + ending.epigraph;
    if (WS.Ui && WS.Ui.confirm) {
      WS.Ui.confirm(full, function () {});
    } else if (console) {
      console.log('[ENDING] ' + full);
    }
    chron('Концовка: ' + ending.title);
    return true;
  }

  // ================================================================ ХУКИ
  WS.boot(function () {
    // победа: расширяем стандартный экран
    WS.Ev.on('game:victory', function () {
      var e = determineEnding();
      if (e) show(e);
    });
    // смерть: поэтичная концовка сияния
    WS.Ev.on('player:die', function (d) {
      if (d && d.cause && /сияни|aurora/i.test(d.cause)) {
        show(ENDINGS.aurora, 'aurora');
      }
    });
    // отметка: сигнальный огонь (финальный квест) — слушаем розжиг на пристани
    WS.Ev.on('fire:lit', function (d) {
      if (!d || !d.x) return;
      // пристань: рядом с мостками/рыбацкими избушками (юг карты)
      if (d.y > 150) {
        flags().signal_fire_lit = true;
        if (WS.Ui && WS.Ui.toast) WS.Ui.toast('Сигнальный огонь на пристани виден с реки!', 'good');
        chron('Зажжён сигнальный огонь пристани');
      }
    });
  }, 'endings:init');

