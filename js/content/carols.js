/**
 * КОЛЯДКИ И СВЯТОЧНЫЕ ПЕСНИ: полные тексты для святок (дни 35-42).
 * Поются у костра, показываются в святки, поднимают рассудок.
 */
(function () {
  'use strict';

  var CAROLS = [];
  function C(o) { CAROLS.push(o); }

  // ================================================================ КЛЯДКИ КЛАССИЧЕСКИЕ
  C({ title: 'Авсень-коляда', kind: 'kolyadka',
    lines: [
      'Авсень, авсень, ты ходил по всем,',
      'По заулочкам, по проулочкам,',
      'Кому песни — кому девки,',
      'А кому-то и полушки-пирога.',
      'Ты, хозяюшка, подай,',
      'Не жалей своих благ,',
      'Зима-то длинна,',
      'А ночь-то темна!'
    ] });
  C({ title: 'Коляда-коляда', kind: 'kolyadka',
    lines: [
      'Коляда, коляда, ты подай пирога,',
      'А кто не подаст — тому холод в дом,',
      'А кто подаст — тому всю жизнь богатство,',
      'Дай, Господь, хозяину здоровья да тепла,',
      'Дом — полную чашу, двор — полон скота,',
      'А нам — уходить до утра.'
    ] });
  C({ title: 'Уж ты, зимушка', kind: 'song',
    lines: [
      'Уж ты, зимушка-зима,',
      'Ты пришла с ногами холодными,',
      'Замела пути-дороги,',
      'Заморозила быка за рога.',
      'Мы по горенкам сидим,',
      'На тебя, зима, глядим,',
      'Ты нас, старая, не трожь —',
      'Мы и так не так уж живы.'
    ] });
  C({ title: 'Как пошли наши ребята', kind: 'kolyadka',
    lines: [
      'Как пошли наши ребята',
      'Колядовать-гулять,',
      'Снег по пояс, ночь до края,',
      'А мороз — до костей.',
      'Хозяин, хозяюшка,',
      'Вы нам вынесите по кусочку,',
      'А не вынесете — мы в окошко',
      'Снегом, снегом, снегом!'
    ] });
  C({ title: 'Ой, мороз, мороз', kind: 'song',
    lines: [
      'Ой, мороз, мороз,',
      'Не морозь меня,',
      'Не морозь меня,',
      'Моего коня.',
      'У меня-то конь',
      'Всю дорогу знал,',
      'А теперь стоит —',
      'Копыт не чует.'
    ] });
  C({ title: 'Святый вечер', kind: 'kolyadka',
    lines: [
      'Святый вечер, добрый вечер,',
      'Добрым людям на здравие,',
      'А худым — на размышление.',
      'Хозяин, вставай,',
      'Дверь отпирай,',
      'Коляду-то встречай,',
      'Тепла-то набирай.'
    ] });

  // ================================================================ ГАДАНИЯ-ПРИПЕВКИ
  C({ title: 'Воск-вощина', kind: 'gadanie',
    lines: [
      'Воск-вощина, вылей-ка судьбу,',
      'Что на рождество — то и на всю зиму,',
      'Куда ляжет полоса —',
      'Туда и жизнь понесётся.'
    ] });
  C({ title: 'Зеркало и свеча', kind: 'gadanie',
    lines: [
      'Свет — от свечи, тьма — от угла,',
      'Суженый-ряженый, приди ко мне ужинать,',
      'Приди по снегу, по звезде,',
      'По скрипу половицы.'
    ] });
  C({ title: 'Петух и зерно', kind: 'gadanie',
    lines: [
      'Клюнет зерно — к сытости,',
      'Клюнет уголь — к стуже,',
      'Клюнет кольцо — к весточке,',
      'А не клюнет — к долгой зиме.'
    ] });

  // ================================================================ СВЯТОЧНЫЙ СТРАХ
  C({ title: 'Как на святки', kind: 'strashilka',
    lines: [
      'Как на святки, по ночам,',
      'Ходит-бродит старый шаман,',
      'Не с бубном — с метлой,',
      'Замечает след за тобой.',
      'Ты в избу — он за тобой,',
      'Ты в печь — он на трубу,',
      'Ты спать — он стеречь.'
    ] });
  C({ title: 'Святочный волк', kind: 'strashilka',
    lines: [
      'В святки волк молчит,',
      'А как промолчит —',
      'Значит, ходит близко,',
      'Значит, слушает.',
      'Кто у печки сидит —',
      'Того не тронет.',
      'А кто в лес пошёл —',
      'Тому — колядка последняя.'
    ] });

  function pick(kind) {
    var pool = CAROLS;
    if (kind) {
      pool = [];
      for (var i = 0; i < CAROLS.length; i++) if (CAROLS[i].kind === kind) pool.push(CAROLS[i]);
    }
    return pool[Math.floor(Math.random() * pool.length)] || null;
  }

  /** Показать колядку у костра (святки). */
  function sing() {
    var c = pick('kolyadka') || pick('song');
    if (!c) return null;
    var text = c.lines.join('\n');
    if (WS.Ui && WS.Ui.confirm) {
      WS.Ui.confirm('Колядка\n\n' + c.title + '\n\n' + text, function () {});
    } else if (WS.Fx && WS.G) {
      WS.Fx.text(c.title, WS.G.player.x, WS.G.player.y - 1, { life: 3 });
    }
    if (WS.G && WS.G.player) {
      WS.G.player.needs.sanity = Math.min(100, WS.G.player.needs.sanity + 6);
    }
    WS.Snd.play('bell', { vol: 0.35 });
    if (WS.G && WS.G.story && WS.G.story.chronicle) {
      WS.G.story.chronicle.push({ day: WS.Time.day(), text: 'Святки: пели «' + c.title + '»' });
    }
    return c;
  }

  WS.boot(function initCarols() {
    // петь колядку: у костра в святки по E (через события)
    WS.Ev.on('mouse:down', function (m) {
      if (!WS.G || !WS.G.running || (WS.Ui && WS.Ui.modal && WS.Ui.modal())) return;
      if (m.button !== 2) return;
      var day = WS.Time.day();
      if (day < 35 || day > 42) return;
      // у огня?
      var p = WS.G.player;
      var lights = WS.World ? WS.World.lightsNear(p.x, p.y, 2.5) : [];
      var nearFire = false;
      for (var i = 0; i < lights.length; i++) if (lights[i].fire) nearFire = true;
      if (!nearFire) return;
      sing();
    });
  }, 'carols:init');

  WS.def('Carols', {
    all: CAROLS,
    pick: pick,
    sing: sing
  });
})();
