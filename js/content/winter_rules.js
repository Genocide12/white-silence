/**
 * ПРАВИЛА ЗИМОВКИ: свод законов выживания Севера.
 * Десять заповедей — показываются при смерти и в справке, каждая с историей.
 * Финальный атмосферный модуль проекта.
 */
(function () {
  'use strict';

  var RULES = [];
  function R(n, title, law, story, why) {
    RULES.push({ n: n, title: title, law: law, story: story, why: why });
  }

  R(1, 'О тепле',
    'Тепло важнее еды, сон важнее тепла, а стены важнее всего.',
    'Ерофей Плотников, ломовой извозчик, помер в феврале, имея полмешка сухарей и ни одной тёплой печи. Сухари нашли нетронутыми.',
    'Еда без тепла не усваивается: тело тратит её на дрожь, а не на жизнь.');

  R(2, 'Об огне',
    'Огонь зажигают ДО темноты. Дрова пилят ДО усталости. Спички делят на два кармана.',
    'Тимофеич рассказывал: две артели ушли на промысел. Одна с полными коробками и пустой печью. Вторая — наоборот. Вернулась вторая.',
    'Промедление с огнём на Севере стоит не часов — градусов.');

  R(3, 'О воде',
    'Пить — кипячёное. Лёд — это вода, которая ждёт, чтобы тебя простудить.',
    'Хворь от сырого снега уложила половину артели в Ширшинскую зимовку в тринадцатом году. Врач сказал: «пили снег, как телята».',
    'Иммунитет, ослабленный холодом, сдаётся первым. Кипяток — бесплатно.');

  R(4, 'О звере',
    'Не бойся зверя — бойся своей жадности к его шкуре.',
    'Ермолай Зверев пошёл на медведя ради шубы. Шуба досталась вдове, а вдове от неё — салфетка.',
    'Преследование раненого зверя — половина всех смертей на промысле.');

  R(5, 'О тишине',
    'Тишина — это не покой. Это когда лес тебя не слышит, а ты его — тоже.',
    'Старухи говорят: перед бедой лес замолкает на полчаса. Проверено в декабре: перед волчьей ночью не скрипнуло ни сучка.',
    'Шум выдаёт, тишина предупреждает. Учитесь различать.');

  R(6, 'О сне',
    'Спать — только за стеной или у огня. Сон на морозе — не сон, а капитуляция.',
    'Фельдшер Аркадий Петрович записывал: «обморожение во сне — самое частое. Тело не чувствует, как сдаётся».',
    'Сон отключает дрожь — последний защитный механизм тела.');

  R(7, 'О запасе',
    'Считай дрова с вечера, еду — с утра, патроны — всегда.',
    'Лавка Прохорыча закрылась с полными полками: товары были, а покупателей — отпускало по одному. Всех перечислять не будем.',
    'Запас без учёта — это надежда. Надежда — плохой интендант.');

  R(8, 'О людях',
    'Не всякому стуку открывай, но и не всякого уходи морить. Север всё видит.',
    'В метель к Акиму постучался беглый. Не открыл. Весной на дорогах стало на одну записку больше, а в душе старика — на одну зиму меньше.',
    'Сожаление грызёт рассудок вернее голода.');

  R(9, 'О терпении',
    'Не решай ничего на закате. Зима любит принимать решения за тебя.',
    '«Вечером — думай, утром — делай» — так учил дед, чью избу вы теперь топите.',
    'Усталость и темнота искажают расчёт. Рассвет — единственный бесплатный советчик.');

  R(10, 'О весне',
    'До парохода не доживают все. Но должен же кто-то донести огонь.',
    'Капитан Ковалёв говорил: «Мы ходим по расписанию не потому, что уверены в пассажирах. Наоборот».',
    'Цель — не пережить зиму. Цель — встретить весну человеком.');

  function pick() {
    return RULES[Math.floor(Math.random() * RULES.length)];
  }

  function byNumber(n) {
    for (var i = 0; i < RULES.length; i++) if (RULES[i].n === n) return RULES[i];
    return null;
  }

  function full() {
    var out = '';
    for (var i = 0; i < RULES.length; i++) {
      var r = RULES[i];
      out += r.n + '. ' + r.title.toUpperCase() + '\n' +
             r.law + '\n\n     ' + r.story + '\n     (' + r.why + ')\n\n';
    }
    return out;
  }

  /** Показать одно правило (тост при сне/загрузке). */
  function showOne() {
    var r = pick();
    if (!r) return null;
    var text = 'Правило ' + r.n + ': ' + r.law;
    if (WS.Ui && WS.Ui.toast) WS.Ui.toast(text, 'info');
    if (WS.G && WS.G.story && WS.G.story.chronicle) {
      WS.G.story.chronicle.push({ day: WS.Time.day(), text: 'Правило ' + r.n + ' вспомнилось' });
    }
    return r;
  }

  WS.boot(function initRules() {
    // правило дня: показывать раз в день при рассвете (с шансом)
    WS.Ev.on('day:dawn', function () {
      if (!WS.G || !WS.G.running) return;
      if (Math.random() > 0.4) return;
      setTimeout(showOne, 3500);
    });
  }, 'rules:init');

  WS.def('Rules', {
    all: RULES,
    pick: pick,
    byNumber: byNumber,
    full: full,
    showOne: showOne
  });
})();
